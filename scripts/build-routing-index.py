#!/usr/bin/env python3
"""Compile the routing keywords of _shared/specialists.md into the hooks' index.

The routing gate of kodflow-hooks (on-tool.sh, pre_agent) refuses a main-thread
dispatch to `general-purpose` whose description names a technology an installed
specialist owns. It runs on every Agent call, in bash 3.2, without Python, so it
reads a flat file rather than the Markdown: one `keyword<TAB>kind<TAB>agent` line
each, `kind` being `word` (a whole lower-case word) or `ext` (a file extension,
matched at the end of a word). The Markdown stays the one place a human edits;
this script is the only writer of the index, and CI checks they agree.

    python3 scripts/build-routing-index.py [root]           write the index
    python3 scripts/build-routing-index.py --check [root]   exit 1 when stale
"""
import pathlib, re, sys

SOURCE = "plugins/kodflow-workflow/skills/_shared/specialists.md"
INDEX = "plugins/kodflow-hooks/hooks/routing-index.tsv"
AGENTS = "plugins/kodflow-specialists/agents"
PLUGIN = "kodflow-specialists"
# Engine agents with no file: always installed, named as the engine names them.
BUILTINS = {"Explore", "Plan"}
HEADER = "# generated by scripts/build-routing-index.py from " + SOURCE + " — do not edit"

WORD = re.compile(r"^[a-z0-9][a-z0-9+_.-]*$")


def rows(text):
    """Yield (agent, [keywords]) from the three-column table of the source."""
    in_table = False
    for line in text.splitlines():
        if line.startswith("| Evidence | Specialist | Keywords |"):
            in_table = True
            continue
        if not in_table:
            continue
        if not line.startswith("|"):
            break
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if set(cells[0]) <= set("-"):
            continue
        if len(cells) != 3:
            raise ValueError(f"routing row without three columns: {line}")
        names = re.findall(r"`([^`]+)`", cells[1])
        if len(names) != 1:
            raise ValueError(f"routing row must name exactly one agent: {line}")
        yield names[0], cells[2].split()


def build(root):
    root = pathlib.Path(root)
    text = (root / SOURCE).read_text()
    out, faults = set(), []
    for agent, words in rows(text):
        if agent in BUILTINS:
            target = agent
        elif (root / AGENTS / f"{agent}.md").is_file():
            target = f"{PLUGIN}:{agent}"
        else:
            faults.append(f"{agent}: no {AGENTS}/{agent}.md and not a built-in")
            continue
        if not words:
            faults.append(f"{agent}: no keywords")
        for w in words:
            if not WORD.match(w.lstrip(".")) or w != w.lower():
                faults.append(f"{agent}: keyword {w!r} is not a lower-case word or extension")
            elif w.startswith("."):
                out.add(f"{w}\text\t{target}")
            elif len(w) < 3:
                faults.append(f"{agent}: keyword {w!r} is shorter than three characters")
            else:
                out.add(f"{w}\tword\t{target}")
    if faults:
        raise ValueError("\n".join(faults))
    # Byte order, as LC_ALL=C sort would give: the gate never sorts at run time
    body = sorted(out, key=lambda s: s.encode())
    return HEADER + "\n" + "\n".join(body) + "\n"


def main(argv):
    check = "--check" in argv
    args = [a for a in argv if a != "--check"]
    root = pathlib.Path(args[0] if args else ".")
    try:
        want = build(root)
    except ValueError as e:
        print(f"routing index: {e}", file=sys.stderr)
        return 1
    path = root / INDEX
    if check:
        if path.is_file() and path.read_text() == want:
            print("routing index up to date")
            return 0
        print(f"{INDEX} is stale: run python3 scripts/build-routing-index.py", file=sys.stderr)
        return 1
    path.write_text(want)
    print(f"wrote {INDEX} ({want.count(chr(10)) - 1} keywords)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
