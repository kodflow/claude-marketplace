#!/usr/bin/env bash
# check-tier-vectors.sh [--write] — the tier judge's shared vectors
# (plugins/kodflow-hooks/tests/fixtures/tier-vectors.jsonl: frontmatter
# fields, mode resolution, Workflow scripts) are read by the shell, the mod
# and Python. A test under `claude plugin test` imports code only and cannot
# open a .jsonl file, so tests/mod/tier-vectors.ts carries the same bytes as
# one string constant.
#
#   (none)    exit 0 when tier-vectors.ts is what --write would write and
#             every line of the fixture is a JSON object with a kind; 1 otherwise
#   --write   rewrites tier-vectors.ts from the fixture
#
# After editing the fixture: --write, then run the mod's tests.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
src="$root/plugins/kodflow-hooks/tests/fixtures/tier-vectors.jsonl"
module="$root/plugins/kodflow-hooks/tests/mod/tier-vectors.ts"
mode="${1:-check}"
case "$mode" in
  check | --write) ;;
  *) echo "usage: check-tier-vectors.sh [--write]" >&2; exit 2 ;;
esac

generate() {
  python3 - "$src" <<'PY'
import json, sys
path = sys.argv[1]
text = open(path, encoding="utf-8", newline="").read()
for n, line in enumerate(text.splitlines(), 1):
    row = json.loads(line)
    if not isinstance(row, dict) or row.get("kind") not in ("frontmatter", "mode", "script"):
        sys.exit(f"{path}:{n}: not an object with kind frontmatter, mode or script")
print("// tier-vectors.ts — GENERATED by scripts/check-tier-vectors.sh --write")
print("// from tests/fixtures/tier-vectors.jsonl, byte for byte: the vectors the")
print("// shell, the mod and Python judges share. Do not edit; rerun the script.")
print(f"\nexport const TIER_VECTORS_JSONL =\n  {json.dumps(text, ensure_ascii=False)};")
PY
}

if [ "$mode" = "--write" ]; then
  generate >"$module"
  echo "$module rewritten"
  exit 0
fi

if ! generate | cmp -s - "$module"; then
  echo "::error::$module is not what --write writes from $src" >&2
  exit 1
fi
echo "tier vectors: tier-vectors.ts matches the fixture"
