#!/usr/bin/env bash
# check-hunt-fixtures.sh [--write] — kodflow-hud reads /hunt's status.json
# through a copy of kodflow-workflow's shared fixtures (a plugin is installed
# alone, so it cannot reach into a sibling's folder), and its tests through
# tests/hunt-fixtures.ts, the same bytes as string constants (a test under
# `claude plugin test` imports code only, it cannot open a .json file).
#
#   (none)    exit 0 when each copy is byte for byte kodflow-workflow's and
#             hunt-fixtures.ts is what --write would write; 1 otherwise
#   --write   copies the fixtures over, then rewrites hunt-fixtures.ts
#
# After /hunt changed its format: --write, then adapt kodflow-hud.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
src="$root/plugins/kodflow-workflow/skills/hunt/tests/fixtures"
dst="$root/plugins/kodflow-hud/tests/fixtures"
module="$root/plugins/kodflow-hud/tests/hunt-fixtures.ts"
names=(status-v1.json status-torn.json status-v99.json)
mode="${1:-check}"
case "$mode" in
  check | --write) ;;
  *) echo "usage: check-hunt-fixtures.sh [--write]" >&2; exit 2 ;;
esac

# The module: one constant a fixture, its text as a JSON string literal
generate() {
  python3 - "$dst" "${names[@]}" <<'PY'
import json, sys
d, names = sys.argv[1], sys.argv[2:]
print("// hunt-fixtures.ts — GENERATED by scripts/check-hunt-fixtures.sh --write")
print("// from tests/fixtures/, itself kodflow-workflow's skills/hunt/tests/fixtures/")
print("// byte for byte: the status.json texts /hunt v1 writes, torn, and of an")
print("// unknown version. Do not edit; rerun the script.")
for n in names:
    const = "STATUS_" + n[len("status-"):-len(".json")].upper()
    text = open(f"{d}/{n}", encoding="utf-8", newline="").read()
    print(f"\nexport const {const} =\n  {json.dumps(text, ensure_ascii=False)};")
PY
}

if [ "$mode" = "--write" ]; then
  mkdir -p "$dst"
  for name in "${names[@]}"; do cp "$src/$name" "$dst/$name"; done
  generate >"$module"
  echo "hunt fixtures copied, $module rewritten"
  exit 0
fi

status=0
for name in "${names[@]}"; do
  if ! cmp -s "$src/$name" "$dst/$name"; then
    echo "::error::$name differs between $src and $dst (or is missing)" >&2
    status=1
  fi
done
if ! generate | cmp -s - "$module"; then
  echo "::error::$module is not what --write writes from the copies" >&2
  status=1
fi
[ "$status" -eq 0 ] && echo "hunt fixtures: kodflow-hud's copies match kodflow-workflow's"
exit "$status"
