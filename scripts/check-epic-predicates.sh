#!/usr/bin/env bash
# check-epic-predicates.sh [--write|--check] — the epic predicates' shared
# cases (plugins/kodflow-hooks/tests/fixtures/epic-predicates.json: closed,
# idle, orphan) are read by lib/epics.jq's test and tests/mod/run-node.ts
# from the file, and by the tests that run under `claude plugin test`, which
# import code only and cannot open a file, through one string constant:
# kodflow-hooks' tests/mod/epic-predicates.ts and kodflow-hud's
# tests/epic-predicates.ts. The fixture is carried as text, byte for byte, so
# a value no JSON writer would keep (1e999) reaches every reader as written.
#
#   --check (default)  exit 0 when both modules are what --write would write
#                      and the fixture holds now, live, data and expect; 1 otherwise
#   --write            rewrites both modules from the fixture
#
# After editing the fixture: --write, then run both plugins' tests.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
src="$root/plugins/kodflow-hooks/tests/fixtures/epic-predicates.json"
modules=(
  "$root/plugins/kodflow-hooks/tests/mod/epic-predicates.ts"
  "$root/plugins/kodflow-hud/tests/epic-predicates.ts"
)
mode="${1:---check}"
case "$mode" in
  --check | --write) ;;
  *) echo "usage: check-epic-predicates.sh [--write|--check]" >&2; exit 2 ;;
esac

generate() {
  python3 - "$src" <<'PY'
import json, sys
path = sys.argv[1]
text = open(path, encoding="utf-8", newline="").read()
data = json.loads(text)
for key in ("now", "live", "data", "expect"):
    if key not in data:
        sys.exit(f"{path}: no {key}")
for key in ("closed", "idle", "orphans"):
    if key not in data["expect"]:
        sys.exit(f"{path}: expect has no {key}")
print("// epic-predicates.ts — GENERATED by scripts/check-epic-predicates.sh --write")
print("// from kodflow-hooks/tests/fixtures/epic-predicates.json, byte for byte: the")
print("// cases closed, idle and orphan share across jq, the mod and kodflow-hud.")
print("// Do not edit; rerun the script.")
print(f"\nexport const EPIC_PREDICATES_JSON =\n  {json.dumps(text, ensure_ascii=False)};")
PY
}

if [ "$mode" = "--write" ]; then
  for m in "${modules[@]}"; do
    generate >"$m"
    echo "$m rewritten"
  done
  exit 0
fi

fail=0
for m in "${modules[@]}"; do
  if ! generate | cmp -s - "$m"; then
    echo "::error::$m is not what --write writes from $src" >&2
    fail=1
  fi
done
[ "$fail" -eq 0 ] || exit 1
echo "epic predicates: both modules match the fixture"
