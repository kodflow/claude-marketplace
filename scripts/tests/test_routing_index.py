#!/usr/bin/env python3
"""build-routing-index.py writes what the gate can read, and refuses the rest.

The gate in on-tool.sh trusts the index blindly: a keyword of two letters
would refuse half the dispatches of a session, an agent that does not exist
would be named as the one to use, and an unsorted file would still be read,
just not reproducibly. So each of those is planted in a fixture and must be
refused, and the committed index must be exactly what the generator writes.
"""
import pathlib, subprocess, sys, tempfile

ROOT = pathlib.Path(__file__).resolve().parents[2]
GEN = ROOT / "scripts" / "build-routing-index.py"
SRC = "plugins/kodflow-workflow/skills/_shared/specialists.md"
OUT = "plugins/kodflow-hooks/hooks/routing-index.tsv"
fails = 0


def check(name, ok, detail=""):
    global fails
    print(("ok   " if ok else "FAIL ") + name + ("" if ok else f" — {detail}"))
    fails += 0 if ok else 1


def fixture(table):
    root = pathlib.Path(tempfile.mkdtemp())
    (root / SRC).parent.mkdir(parents=True)
    (root / OUT).parent.mkdir(parents=True)
    agents = root / "plugins/kodflow-specialists/agents"
    agents.mkdir(parents=True)
    (agents / "developer-specialist-go.md").write_text("---\nname: developer-specialist-go\n---\n")
    (root / SRC).write_text("# t\n\n| Evidence | Specialist | Keywords |\n|---|---|---|\n" + table + "\n\nprose\n")
    return root


def run(root, *args):
    return subprocess.run([sys.executable, str(GEN), *args, str(root)], capture_output=True, text=True)


# The committed index is current
r = run(ROOT, "--check")
check("committed index matches specialists.md", r.returncode == 0, r.stderr.strip())

lines = (ROOT / OUT).read_text().splitlines()
body = lines[1:]
check("header first, then rows", lines[0].startswith("# generated by"), lines[0])
check("rows in byte order (LC_ALL=C)", body == sorted(body, key=lambda s: s.encode()))
check("three tab-separated fields per row", all(len(l.split("\t")) == 3 for l in body))
check("every kind is word or ext", all(l.split("\t")[1] in ("word", "ext") for l in body))
agents = {l.split("\t")[2] for l in body}
for a in sorted(agents):
    if ":" in a:
        plugin, name = a.split(":", 1)
        check(f"{a} exists", (ROOT / "plugins" / plugin / "agents" / f"{name}.md").is_file())
for want in ("kodflow-specialists:tooling-specialist-ansible", "kodflow-specialists:tooling-specialist-gitlab-ci",
             "kodflow-specialists:data-specialist-valkey", "kodflow-specialists:domain-specialist-telecom",
             "kodflow-specialists:domain-specialist-systemd", "kodflow-specialists:devops-executor-linux",
             "kodflow-specialists:developer-specialist-protobuf", "Explore"):
    check(f"{want} is routed", want in agents)

# A good fixture builds; extensions keep their dot, words their kind
root = fixture("| `.go` | `developer-specialist-go` | golang .go |\n| x | `Explore` | locate |")
r = run(root)
got = (root / OUT).read_text().splitlines()[1:] if r.returncode == 0 else []
check("fixture builds", r.returncode == 0, r.stderr.strip())
check("fixture rows", got == [".go\text\tkodflow-specialists:developer-specialist-go",
                              "golang\tword\tkodflow-specialists:developer-specialist-go",
                              "locate\tword\tExplore"], got)
check("--check passes right after a build", run(root, "--check").returncode == 0)
(root / OUT).write_text((root / OUT).read_text() + "stray\tword\tExplore\n")
check("--check fails on a hand edit", run(root, "--check").returncode == 1)

for name, table in (
    ("a two-letter word", "| x | `developer-specialist-go` | go |"),
    ("an unknown agent", "| x | `developer-specialist-cobol` | cobol |"),
    ("an upper-case keyword", "| x | `developer-specialist-go` | Golang |"),
    ("a row with no keywords", "| x | `developer-specialist-go` |  |"),
    ("a row naming two agents", "| x | `developer-specialist-go` `Explore` | golang |"),
):
    r = run(fixture(table))
    check(f"refuses {name}", r.returncode == 1, r.stdout + r.stderr)

print(f"{fails} failure(s)")
sys.exit(1 if fails else 0)
